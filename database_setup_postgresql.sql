CREATE TABLE Organizers_007 (
    organizer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    email VARCHAR(100) NOT NULL UNIQUE,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(20),
    company_name VARCHAR(100),
    approval_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (approval_status IN ('pending', 'approved', 'rejected', 'banned')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Venues_007 (
    venue_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_name VARCHAR(100) NOT NULL,
    address VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    state VARCHAR(50),
    zip_code VARCHAR(20),
    capacity INTEGER NOT NULL CONSTRAINT venues_007_capacity_positive CHECK (capacity > 0),
    amenities TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Events_007 (
    event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizer_id INTEGER NOT NULL REFERENCES Organizers_007(organizer_id),
    venue_id INTEGER NOT NULL REFERENCES Venues_007(venue_id),
    event_name VARCHAR(200) NOT NULL,
    event_description TEXT,
    event_date TIMESTAMP NOT NULL,
    end_date TIMESTAMP,
    ticket_price NUMERIC(10, 2) NOT NULL CONSTRAINT events_007_price_nonnegative CHECK (ticket_price >= 0),
    max_capacity INTEGER NOT NULL CONSTRAINT events_007_capacity_positive CHECK (max_capacity > 0),
    event_status VARCHAR(20) NOT NULL DEFAULT 'draft'
        CHECK (event_status IN ('draft', 'published', 'cancelled', 'completed')),
    CONSTRAINT events_007_date_range CHECK (end_date IS NULL OR end_date >= event_date),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Attendees_007 (
    attendee_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(20),
    address VARCHAR(255),
    loyalty_points INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Vendors_007 (
    vendor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_name VARCHAR(100) NOT NULL,
    vendor_type VARCHAR(50) NOT NULL,
    contact_person VARCHAR(100),
    email VARCHAR(100),
    phone VARCHAR(20),
    rating NUMERIC(3, 2) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Tickets_007 (
    ticket_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES Events_007(event_id),
    attendee_id INTEGER NOT NULL REFERENCES Attendees_007(attendee_id),
    ticket_number VARCHAR(40) NOT NULL UNIQUE,
    ticket_status VARCHAR(20) NOT NULL DEFAULT 'booked'
        CHECK (ticket_status IN ('booked', 'confirmed', 'cancelled', 'checked_in', 'used')),
    booking_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    check_in_time TIMESTAMP
);

CREATE TABLE Payments_007 (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id INTEGER NOT NULL UNIQUE REFERENCES Tickets_007(ticket_id),
    attendee_id INTEGER NOT NULL REFERENCES Attendees_007(attendee_id),
    amount NUMERIC(10, 2) NOT NULL,
    payment_method VARCHAR(50) NOT NULL
        CHECK (payment_method IN ('credit_card', 'debit_card', 'cash', 'online')),
    payment_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (payment_status IN ('pending', 'completed', 'failed', 'refund_pending', 'refunded')),
    payment_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Event_Vendors_007 (
    event_vendor_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id INTEGER NOT NULL REFERENCES Events_007(event_id),
    vendor_id INTEGER NOT NULL REFERENCES Vendors_007(vendor_id),
    service_description TEXT,
    service_cost NUMERIC(10, 2),
    assigned_date DATE,
    CONSTRAINT unique_event_vendor UNIQUE (event_id, vendor_id)
);

CREATE TABLE Audit_Log_007 (
    audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER,
    user_type VARCHAR(20) NOT NULL CHECK (user_type IN ('admin', 'organizer', 'attendee')),
    action_type VARCHAR(50) NOT NULL,
