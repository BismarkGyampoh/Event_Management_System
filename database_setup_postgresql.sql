CREATE FUNCTION CalculateEventRevenue_007(p_event_id INTEGER)
RETURNS NUMERIC(15, 2)
LANGUAGE SQL
STABLE
AS $$
    SELECT COALESCE(SUM(p.amount), 0)::NUMERIC(15, 2)
    FROM Payments_007 p
    INNER JOIN Tickets_007 t ON t.ticket_id = p.ticket_id
    WHERE t.event_id = p_event_id
      AND p.payment_status = 'completed'
      AND t.ticket_status <> 'cancelled'
$$;

CREATE FUNCTION GetLoyaltyTier_007(p_loyalty_points INTEGER)
RETURNS VARCHAR(20)
LANGUAGE SQL
IMMUTABLE
AS $$
    SELECT CASE
        WHEN p_loyalty_points >= 1000 THEN 'Platinum'
        WHEN p_loyalty_points >= 500 THEN 'Gold'
        WHEN p_loyalty_points >= 100 THEN 'Silver'
        ELSE 'Bronze'
    END::VARCHAR(20)
$$;

CREATE VIEW EventSummary_007 AS
SELECT
    e.event_id,
    e.event_name,
    e.event_date,
    e.event_status,
    e.ticket_price,
    e.max_capacity,
    o.full_name AS organizer_name,
    o.email AS organizer_email,
    v.venue_name,
    v.city,
    v.capacity,
    COUNT(t.ticket_id) AS tickets_sold,
    e.max_capacity - COUNT(t.ticket_id) AS tickets_available,
    COALESCE(SUM(CASE WHEN t.ticket_status <> 'cancelled' THEN p.amount ELSE 0 END), 0) AS total_revenue
FROM Events_007 e
INNER JOIN Organizers_007 o ON e.organizer_id = o.organizer_id
INNER JOIN Venues_007 v ON e.venue_id = v.venue_id
LEFT JOIN Tickets_007 t ON e.event_id = t.event_id
LEFT JOIN Payments_007 p ON t.ticket_id = p.ticket_id AND p.payment_status = 'completed'
GROUP BY e.event_id, o.organizer_id, v.venue_id;

CREATE VIEW RevenueByEvent_007 AS
SELECT
    e.event_id,
    e.event_name,
    e.event_date,
    o.full_name AS organizer_name,
    COUNT(t.ticket_id) AS total_tickets,
    SUM(CASE WHEN t.ticket_status <> 'cancelled' THEN 1 ELSE 0 END) AS valid_tickets,
    COALESCE(SUM(CASE WHEN t.ticket_status <> 'cancelled' AND p.payment_status = 'completed' THEN p.amount ELSE 0 END), 0) AS total_revenue,
    CASE WHEN COUNT(t.ticket_id) > 0
         THEN COALESCE(SUM(CASE WHEN t.ticket_status <> 'cancelled' AND p.payment_status = 'completed' THEN p.amount ELSE 0 END), 0) / COUNT(t.ticket_id)
         ELSE 0
    END AS avg_ticket_price
FROM Events_007 e
INNER JOIN Organizers_007 o ON e.organizer_id = o.organizer_id
LEFT JOIN Tickets_007 t ON e.event_id = t.event_id
LEFT JOIN Payments_007 p ON t.ticket_id = p.ticket_id
GROUP BY e.event_id, o.organizer_id;

