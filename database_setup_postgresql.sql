CREATE FUNCTION audit_ticket_change_007()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO Audit_Log_007 (user_id, user_type, action_type, table_name, record_id, new_values)
        VALUES (
            NEW.attendee_id, 'attendee', 'INSERT', 'Tickets_007', NEW.ticket_id,
            to_jsonb(NEW)
        );
    ELSIF OLD.ticket_status IS DISTINCT FROM NEW.ticket_status
          AND NEW.ticket_status = 'cancelled' THEN
        INSERT INTO Audit_Log_007 (user_id, user_type, action_type, table_name, record_id, old_values, new_values)
        VALUES (
            NEW.attendee_id, 'attendee', 'UPDATE', 'Tickets_007', NEW.ticket_id,
            to_jsonb(OLD), to_jsonb(NEW)
        );
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_ticket_audit_insert
AFTER INSERT ON Tickets_007
FOR EACH ROW EXECUTE FUNCTION audit_ticket_change_007();

CREATE TRIGGER trg_ticket_audit_cancel
AFTER UPDATE ON Tickets_007
FOR EACH ROW EXECUTE FUNCTION audit_ticket_change_007();

