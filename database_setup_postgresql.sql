CREATE OR REPLACE FUNCTION ExpireReservations_007()
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_expired_count INTEGER;
BEGIN
    UPDATE Tickets_007
    SET ticket_status = 'expired'
    WHERE ticket_status = 'booked'
      AND expires_at IS NOT NULL
      AND expires_at <= CURRENT_TIMESTAMP;
    GET DIAGNOSTICS v_expired_count = ROW_COUNT;

    UPDATE Payments_007 p
    SET payment_status = 'failed'
    FROM Tickets_007 t
    WHERE p.ticket_id = t.ticket_id
      AND t.ticket_status = 'expired'
      AND p.payment_status = 'pending';

    UPDATE BookingOrders_007
    SET status = 'expired', updated_at = CURRENT_TIMESTAMP
    WHERE status = 'pending' AND expires_at <= CURRENT_TIMESTAMP;

    UPDATE EventWaitlist_007
    SET status = 'expired'
    WHERE status = 'invited' AND invite_expires_at <= CURRENT_TIMESTAMP;

    PERFORM PromoteWaitlist_007(NULL);

    RETURN v_expired_count;
END;
$$;

CREATE OR REPLACE FUNCTION PromoteWaitlist_007(p_event_id INTEGER DEFAULT NULL)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_event RECORD;
    v_waitlist_id INTEGER;
    v_active_tickets BIGINT;
    v_active_invites BIGINT;
    v_available INTEGER;
    v_promoted INTEGER := 0;
    v_slot INTEGER;
BEGIN
    FOR v_event IN
        SELECT e.event_id, e.max_capacity
        FROM Events_007 e
        WHERE e.event_status = 'published'
          AND e.event_date > CURRENT_TIMESTAMP
          AND (p_event_id IS NULL OR e.event_id = p_event_id)
          AND EXISTS (SELECT 1 FROM EventWaitlist_007 w WHERE w.event_id = e.event_id AND w.status = 'waiting')
        ORDER BY e.event_id
        FOR UPDATE OF e
    LOOP
        SELECT (SELECT COUNT(*) FROM Tickets_007 t
                WHERE t.event_id = v_event.event_id AND t.ticket_status NOT IN ('cancelled', 'expired'))
             + COALESCE((SELECT SUM(bi.quantity) FROM BookingItems_007 bi JOIN BookingOrders_007 b ON b.booking_id = bi.booking_id
                WHERE b.event_id = v_event.event_id AND b.status = 'pending' AND b.expires_at > CURRENT_TIMESTAMP), 0)
        INTO v_active_tickets;
        SELECT COUNT(*) INTO v_active_invites FROM EventWaitlist_007 w
        WHERE w.event_id = v_event.event_id AND w.status = 'invited'
          AND w.invite_expires_at > CURRENT_TIMESTAMP;
        v_available := GREATEST(0, v_event.max_capacity - v_active_tickets - v_active_invites);

        FOR v_slot IN 1..v_available LOOP
            SELECT w.waitlist_id INTO v_waitlist_id
            FROM EventWaitlist_007 w
            WHERE w.event_id = v_event.event_id AND w.status = 'waiting'
            ORDER BY w.created_at, w.waitlist_id
            LIMIT 1
            FOR UPDATE SKIP LOCKED;
            EXIT WHEN NOT FOUND;

            UPDATE EventWaitlist_007
            SET status = 'invited', invited_at = CURRENT_TIMESTAMP,
                invite_expires_at = CURRENT_TIMESTAMP + INTERVAL '24 hours'
            WHERE waitlist_id = v_waitlist_id;
            v_promoted := v_promoted + 1;
        END LOOP;
    END LOOP;

    RETURN v_promoted;
END;
$$;
