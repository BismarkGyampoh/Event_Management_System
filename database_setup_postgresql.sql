CREATE OR REPLACE FUNCTION BookTicket_007(p_event_id INTEGER, p_attendee_id INTEGER, p_payment_method VARCHAR)
RETURNS TABLE(ticket_id INTEGER, ticket_number VARCHAR, amount NUMERIC, status VARCHAR, message TEXT)
LANGUAGE plpgsql
AS $$
DECLARE
    v_ticket_price NUMERIC(10, 2);
    v_max_capacity INTEGER;
    v_event_status VARCHAR(20);
    v_event_date TIMESTAMP;
    v_current_bookings BIGINT;
    v_new_ticket_id INTEGER;
    v_ticket_number VARCHAR(40);
BEGIN
    IF p_payment_method IS DISTINCT FROM 'cash' THEN
        RETURN QUERY SELECT NULL::INTEGER, NULL::VARCHAR, NULL::NUMERIC,
            'Error'::VARCHAR, 'Only pay-in-person bookings are available until online payments are configured.'::TEXT;
        RETURN;
    END IF;

    SELECT e.ticket_price, e.max_capacity, e.event_status, e.event_date
    INTO v_ticket_price, v_max_capacity, v_event_status, v_event_date
    FROM Events_007 e
    WHERE e.event_id = p_event_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN QUERY SELECT NULL::INTEGER, NULL::VARCHAR, NULL::NUMERIC, 'Error'::VARCHAR, 'Event not found.'::TEXT;
        RETURN;
    END IF;

    IF v_event_status <> 'published' OR v_event_date <= CURRENT_TIMESTAMP THEN
        RETURN QUERY SELECT NULL::INTEGER, NULL::VARCHAR, NULL::NUMERIC, 'Error'::VARCHAR, 'Event is not available for booking.'::TEXT;
        RETURN;
    END IF;

    IF EXISTS (
        SELECT 1 FROM Tickets_007 t
        WHERE t.event_id = p_event_id
          AND t.attendee_id = p_attendee_id
          AND t.ticket_status <> 'cancelled'
    ) THEN
        RETURN QUERY SELECT NULL::INTEGER, NULL::VARCHAR, NULL::NUMERIC, 'Error'::VARCHAR, 'You already have an active booking for this event.'::TEXT;
        RETURN;
    END IF;

    SELECT COUNT(*) INTO v_current_bookings
    FROM Tickets_007 t
    WHERE t.event_id = p_event_id AND t.ticket_status <> 'cancelled';

    IF v_current_bookings >= v_max_capacity THEN
        RETURN QUERY SELECT NULL::INTEGER, NULL::VARCHAR, NULL::NUMERIC, 'Error'::VARCHAR, 'Event is fully booked.'::TEXT;
        RETURN;
    END IF;

    v_ticket_number := 'TKT-' || p_event_id || '-' ||
        TO_CHAR(CLOCK_TIMESTAMP(), 'YYYYMMDDHH24MISSMS') || '-' ||
        LPAD(FLOOR(RANDOM() * 1000000)::INTEGER::TEXT, 6, '0');

    INSERT INTO Tickets_007 (event_id, attendee_id, ticket_number, ticket_status)
    VALUES (p_event_id, p_attendee_id, v_ticket_number, 'booked')
    RETURNING Tickets_007.ticket_id INTO v_new_ticket_id;

    INSERT INTO Payments_007 (ticket_id, attendee_id, amount, payment_method, payment_status)
    VALUES (v_new_ticket_id, p_attendee_id, v_ticket_price, 'cash', 'pending');

    RETURN QUERY SELECT v_new_ticket_id, v_ticket_number, v_ticket_price, 'Success'::VARCHAR,
        'Booking reserved. Payment is pending and your ticket becomes valid after the organizer confirms payment.'::TEXT;
EXCEPTION WHEN unique_violation THEN
    RETURN QUERY SELECT NULL::INTEGER, NULL::VARCHAR, NULL::NUMERIC, 'Error'::VARCHAR, 'You already have an active booking for this event.'::TEXT;
WHEN OTHERS THEN
    RAISE LOG 'BookTicket_007 failed: %', SQLERRM;
    RETURN QUERY SELECT NULL::INTEGER, NULL::VARCHAR, NULL::NUMERIC, 'Error'::VARCHAR,
        'Booking could not be completed. Please try again.'::TEXT;
END;
$$;

CREATE OR REPLACE FUNCTION CancelBooking_007(p_ticket_id INTEGER, p_attendee_id INTEGER)
RETURNS TABLE(ticket_id INTEGER, status VARCHAR, message TEXT)
LANGUAGE plpgsql
AS $$
DECLARE
    v_ticket_status VARCHAR(20);
    v_payment_status VARCHAR(20);
    v_event_date TIMESTAMP;
BEGIN
    SELECT t.ticket_status, p.payment_status, e.event_date
    INTO v_ticket_status, v_payment_status, v_event_date
    FROM Tickets_007 t
    INNER JOIN Events_007 e ON e.event_id = t.event_id
    LEFT JOIN Payments_007 p ON p.ticket_id = t.ticket_id
    WHERE t.ticket_id = p_ticket_id AND t.attendee_id = p_attendee_id
    FOR UPDATE OF t;

    IF NOT FOUND THEN
        RETURN QUERY SELECT NULL::INTEGER, 'Error'::VARCHAR, 'Booking not found.'::TEXT;
        RETURN;
    END IF;

    IF v_ticket_status = 'cancelled' THEN
        RETURN QUERY SELECT NULL::INTEGER, 'Error'::VARCHAR, 'Booking is already cancelled.'::TEXT;
        RETURN;
    END IF;

    IF v_ticket_status IN ('checked_in', 'used') OR v_event_date <= CURRENT_TIMESTAMP THEN
        RETURN QUERY SELECT NULL::INTEGER, 'Error'::VARCHAR, 'This booking can no longer be cancelled online.'::TEXT;
        RETURN;
    END IF;

    UPDATE Tickets_007 SET ticket_status = 'cancelled' WHERE Tickets_007.ticket_id = p_ticket_id;

    IF v_payment_status IS NOT NULL THEN
        UPDATE Payments_007
        SET payment_status = CASE
            WHEN v_payment_status = 'completed' THEN 'refund_pending'
            ELSE 'failed'
        END
        WHERE Payments_007.ticket_id = p_ticket_id;
    END IF;

    IF v_payment_status = 'completed' THEN
        RETURN QUERY SELECT p_ticket_id, 'Success'::VARCHAR,
            'Booking cancelled. The organizer must process and confirm any cash refund.'::TEXT;
    ELSE
        RETURN QUERY SELECT p_ticket_id, 'Success'::VARCHAR, 'Booking cancelled.'::TEXT;
    END IF;
EXCEPTION WHEN OTHERS THEN
    RAISE LOG 'CancelBooking_007 failed: %', SQLERRM;
    RETURN QUERY SELECT NULL::INTEGER, 'Error'::VARCHAR,
        'Booking cancellation could not be completed. Please try again.'::TEXT;
END;
$$;

